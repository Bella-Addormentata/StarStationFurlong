// The fold bundle: src/foldEntry.ts (the pages' own computedFold, and what it
// imports) as one script QuickJS can evaluate, the node's copy of the fold.
//
// `buildFoldBundle()` returns the text; scripts/build-fold-bundle.mjs writes
// it to ssf-p2p-node/fold/fold.min.js, and src/foldBundle.test.ts builds it
// again and fails when the checked-in file differs (so a change to the fold
// that is not bundled fails CI). The node's cargo jobs read the checked-in
// file (include_str!), so they need no Node.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
export const ROOT = resolve(here, '..');
export const BUNDLE_PATH = resolve(ROOT, 'ssf-p2p-node/fold/fold.min.js');

const BANNER =
  '/* GENERATED by scripts/build-fold-bundle.mjs from src/foldEntry.ts: do not edit. ' +
  'Run `npm run build:fold` after a change to the fold. */';

/** The bundle's text, and the source files that went into it (paths from the project root). */
export async function buildFoldBundle() {
  const result = await build({
    entryPoints: [resolve(ROOT, 'src/foldEntry.ts')],
    bundle: true,
    write: false,
    metafile: true,
    format: 'iife',
    globalName: 'SSFFold',
    platform: 'neutral',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'warning',
    // Node's sha256 is the host's (scripts/fold-sha-shim.mjs).
    plugins: [
      {
        name: 'fold-sha-shim',
        setup(b) {
          b.onResolve({ filter: /^@noble\/hashes\/sha256(\.js)?$/ }, () => ({ path: resolve(here, 'fold-sha-shim.mjs') }));
        },
      },
    ],
  });
  if (result.outputFiles.length !== 1) throw new Error('the fold bundle came out as more than one file');
  return { text: result.outputFiles[0].text, inputs: Object.keys(result.metafile.inputs).sort() };
}
